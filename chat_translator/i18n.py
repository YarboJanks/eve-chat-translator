LANGUAGES = [("en", "English"), ("zh", "中文")]


def tr(lang: str, key: str, **kw) -> str:
    s = STRINGS.get(lang, STRINGS["en"]).get(key) or STRINGS["en"][key]
    return s.format(**kw) if kw else s


def other(lang: str) -> str:
    return "zh" if lang == "en" else "en"
